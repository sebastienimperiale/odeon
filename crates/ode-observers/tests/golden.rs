#[test]
fn kepler_mu_lorenz_and_rod_trackers_and_spring_mass_filter() {
    let g = golden();
    let p = Progress::default();

    let c = &g["kepler_mu_tracker"];
    let x0 = augmented_state(perihelion_state(0.3), 0.1);
    let model = ModelSpec::KeplerMu { params: KeplerMuParams::default(), observation: KeplerObservation::Q1 };
    let r = twin(model.clone(), &x0, 0.01, 30, NoiseModel::Uniform { half_width: 0.02 }, 5000, None).reference(&p);
    check("kepler_mu_tracker", "reference", &r.states, &c["reference"], 0.0);
    check("kepler_mu_tracker", "observations", &r.observations, &c["observations"], 0.0);
    let mut cfg = cfg_from(&["q_1", "q_2", "p_1", "p_2", "θ"], vec![None; 5], &[(0, 4)], &x0);
    for (d, v) in cfg.vars.iter_mut().enumerate() {
        v.sigma = if d < 4 { 1000.0 } else { 1.0 };
        v.x0 = if d < 4 { x0[d] } else { 0.0 };
        v.q = 0.0;
    }
    let out = run_tracker_spec(&model, &r, &cfg, &p);
    check("kepler_mu_tracker", "estimates", &out.estimates, &c["estimates"], 0.0);

    let c = &g["lorenz_tracker"];
    let x0 = [-3.716171, -4.204785, 20.339103];
    let model = ModelSpec::Lorenz { params: LorenzParams::default(), observation: LorenzObservation::X };
    let r = twin(model.clone(), &x0, 0.01, 50, NoiseModel::Gaussian { std: 0.1 }, 5001, None).reference(&p);
    check("lorenz_tracker", "reference", &r.states, &c["reference"], 0.0);
    check("lorenz_tracker", "observations", &r.observations, &c["observations"], 0.0);
    let mut cfg = cfg_from(&["x", "y", "z"], vec![None; 3], &[(0, 1)], &x0);
    for v in &mut cfg.vars {
        v.sigma = 1.0;
        v.x0 += 1.0;
    }
    let out = run_tracker_spec(&model, &r, &cfg, &p);
    check("lorenz_tracker", "estimates", &out.estimates, &c["estimates"], 0.0);

    let c = &g["spring_mass_filter"];
    let x0 = [0.0, 0.15, 0.0, 0.0, 0.3];
    let model = ModelSpec::SpringMass { n: 2, params: SpringMassParams::default(), obs: 1 };
    let r = twin(model.clone(), &x0, 0.02, 3, NoiseModel::Gaussian { std: 0.01 }, 6021, None).reference(&p);
    check("spring_mass_filter", "reference", &r.states, &c["reference"], 0.0);
    check("spring_mass_filter", "observations", &r.observations, &c["observations"], 0.0);
    let mut cfg = cfg_from(&["y_1", "y_2", "v_1", "v_2", "θ"], vec![None; 5], &[(0, 4)], &x0);
    for (d, v) in cfg.vars.iter_mut().enumerate() {
        v.sigma = 1.0;
        v.n_el = 2;
        v.p_ord = 2;
        if d == 4 {
            v.domain = (-1.0, 1.0);
            v.q = 0.0;
            v.x0 = 0.0;
        }
    }
    cfg.n_snapshots = 2;
    let out = run_filter_spec(&model, &r, &cfg, &p);
    check("spring_mass_filter", "estimates", &out.estimates, &c["estimates"], 0.0);
    check("spring_mass_filter", "marginal", &out.marginals.last().unwrap()[0], &c["marginal"], 0.0);

    let c = &g["pendulum_rod_tracker"];
    let x0 = [2.453, -2.7727, 0.0, 0.0];
    let model = ModelSpec::PendulumRod { params: PendulumRodParams::default() };
    let r = twin(model.clone(), &x0, 0.01, 40, NoiseModel::Gaussian { std: 0.02 }, 3000, None).reference(&p);
    check("pendulum_rod_tracker", "reference", &r.states, &c["reference"], 0.0);
    check("pendulum_rod_tracker", "observations", &r.observations, &c["observations"], 0.0);
    let mut cfg = cfg_from(&["q_1", "q_2", "p_1", "p_2"], vec![Some((-PI, PI)), Some((-PI, PI)), None, None], &[(0, 2)], &x0);
    for v in &mut cfg.vars {
        v.sigma = 1.0;
    }
    let out = run_tracker_spec(&model, &r, &cfg, &p);
    check("pendulum_rod_tracker", "estimates", &out.estimates, &c["estimates"], 0.0);
}

/// The generator's `Reference` is what the old models produced, so the
/// `Reference::twin` of a model equals a hand-run of its flow.
#[test]
fn reference_twin_is_the_flow_iterated() {
    let sys = LorenzSystem::new(0.01, LorenzObservation::Y);
    let r = Reference::twin(&sys, [1.0, 1.0, 1.0], 20, NoiseModel::None, 0, None, &Progress::default());
    let mut x = [1.0, 1.0, 1.0];
    for n in 0..20 {
        x = sys.flow(&x);
        assert_eq!(r.states[n + 1], x.to_vec());
        assert_eq!(r.observations[n + 1], vec![x[1]]);
    }
}
