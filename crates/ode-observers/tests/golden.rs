fn golden() -> serde_json::Map<String, Value> {
    let text = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/tests/golden/stateful.json")).unwrap();
    serde_json::from_str::<Value>(&text).unwrap().as_object().unwrap().clone()
}

/// Compare a serializable value with the recorded one, recursively, to a
/// relative tolerance (`0.0` = bit for bit). The tolerance is relative to
/// the larger of the two values *and* of the field's overall magnitude, so
/// that a value of 1e-14 in a density whose maximum is 1 (a box corner,
/// where the interpolation's round-off dominates) is compared absolutely.
fn check<T: serde::Serialize>(case: &str, field: &str, actual: &T, expected: &Value, tol: f64) {
    fn magnitude(v: &Value) -> f64 {
        match v {
            Value::Array(a) => a.iter().map(magnitude).fold(0.0, f64::max),
            Value::Number(n) => n.as_f64().unwrap().abs(),
            _ => 0.0,
        }
    }
    fn go(path: &str, a: &Value, e: &Value, tol: f64, scale: f64) {
        match (a, e) {
            (Value::Array(a), Value::Array(e)) => {
                assert_eq!(a.len(), e.len(), "{path}: length {} vs {}", a.len(), e.len());
                for (i, (x, y)) in a.iter().zip(e).enumerate() {
                    go(&format!("{path}[{i}]"), x, y, tol, scale);
                }
            }
            (Value::Number(a), Value::Number(e)) => {
                let (a, e) = (a.as_f64().unwrap(), e.as_f64().unwrap());
                let ok = if tol == 0.0 {
                    a.to_bits() == e.to_bits() || a == e
                } else {
                    (a - e).abs() <= tol * a.abs().max(e.abs()).max(scale)
                };
                assert!(ok, "{path}: {a:e} vs golden {e:e}");
            }
            (Value::Null, Value::Null) => {}
            (Value::Bool(a), Value::Bool(e)) => assert_eq!(a, e, "{path}"),
            _ => panic!("{path}: {a} vs {e}"),
        }
    }
    let actual = serde_json::to_value(actual).unwrap();
    go(&format!("{case}.{field}"), &actual, expected, tol, magnitude(expected));
}

/// A configuration as the recording made it: the defaults from eleven
/// copies of `x0` (not from the real trajectory).
fn cfg_from(labels: &[&str], periodic: Vec<Option<(f64, f64)>>, pairs: &[(usize, usize)], x0: &[f64]) -> FilterConfig {
    FilterConfig::defaults(labels.iter().map(|s| s.to_string()).collect(), periodic, pairs, &vec![x0.to_vec(); 11])
}

fn twin(model: ModelSpec, x0: &[f64], dt: f64, steps: usize, noise: NoiseModel, seed: u64, walk: Option<Walk>) -> TwinSpec {
    TwinSpec { model, x0: x0.to_vec(), dt, steps, noise, seed, walk }
}

const SPRING_TOL: f64 = 1e-9;

#[test]
fn spring_filter_tracker_window_and_particles() {
    let g = golden();
    let p = Progress::default();
    let dt = 0.02;
    let model = ModelSpec::Spring { n: 1, rho: 1.0, a: 1.0, obs: 0 };
    let noise = NoiseModel::Gaussian { std: 0.01 };
    let mut cfg = cfg_from(&["y_1", "v_1"], vec![None; 2], &[(0, 1)], &[0.15, 0.0]);
    for v in &mut cfg.vars {
        v.sigma = 5.0;
        v.half_width = 0.8;
    }
    cfg.n_snapshots = 3;

    let c = &g["spring_filter"];
    let r = twin(model.clone(), &[0.15, 0.0], dt, 20, noise, 1000, None).reference(&p);
    check("spring_filter", "reference", &r.states, &c["reference"], SPRING_TOL);
    check("spring_filter", "observations", &r.observations, &c["observations"], SPRING_TOL);
    let out = run_filter_spec(&model, &r, &cfg, &p);
    check("spring_filter", "estimates", &out.estimates, &c["estimates"], SPRING_TOL);
    check("spring_filter", "marginal", &out.marginals.last().unwrap()[0], &c["marginal"], SPRING_TOL);
    check("spring_filter", "saved_steps", &out.saved_steps, &c["saved_steps"], 0.0);
    check("spring_filter", "axes", &out.axes, &c["axes"], 0.0);

    let c = &g["spring_tracker"];
    let r = twin(model.clone(), &[0.15, 0.0], dt, 200, noise, 1000, None).reference(&p);
    let out = run_tracker_spec(&model, &r, &cfg, &p);
    check("spring_tracker", "estimates", &out.estimates, &c["estimates"], SPRING_TOL);
    check("spring_tracker", "covariances", &out.covariances, &c["covariances"], SPRING_TOL);
    check("spring_tracker", "reference", &out.reference, &c["reference"], SPRING_TOL);

    let c = &g["spring_window"];
    let r = twin(model.clone(), &[0.15, 0.0], dt, 100, noise, 1000, None).reference(&p);
    let out = run_box_spec(&model, &r, &cfg, &p);
    check("spring_window", "estimates", &out.window.estimates, &c["estimates"], SPRING_TOL);
    check("spring_window", "centers", &out.centers, &c["centers"], SPRING_TOL);
    check("spring_window", "marginal", &out.window.marginals.last().unwrap()[0], &c["marginal"], SPRING_TOL);
    check("spring_window", "reference", &out.window.reference, &c["reference"], SPRING_TOL);

    let c = &g["spring_particles"];
    let r = twin(model, &[0.15, 0.0], dt, 30, noise, 1000, None).reference(&p);
    let pp = ParticleParams::<2> {
        n_particles: 50,
        center: [0.15, 0.0],
        sigma: [5.0; 2],
        domain: [(-0.5, 0.5); 2],
        periodic: [false; 2],
        eps: 0.01,
        q_diag: [1.0; 2],
        noise_scale: 1.0,
        gamma: 1.0,
        seed: 11,
    };
    let mut ps = ParticleSystem::<2, _>::new(SpringSystem::new(1, 1.0, 1.0, dt, |x: &[f64]| x[0]), pp);
    for y in &r.observations[..30] {
        ps.forward(y);
    }
    check("spring_particles", "positions", &ps.positions(), &c["positions"], SPRING_TOL);
    check("spring_particles", "budgets", &ps.budgets(), &c["budgets"], 0.0);
    check("spring_particles", "spent", &ps.spent(), &c["spent"], SPRING_TOL);
    assert_eq!(ps.births() as u64, c["births"].as_u64().unwrap());
    check("spring_particles", "reference", &r.states, &c["reference"], SPRING_TOL);
}

