//! Golden tests of the stateless-model refactor (2026-09-14): every
//! estimator, on every model, must reproduce the outputs recorded from the
//! previous implementation — where a model carried its own trajectory and
//! noisy observation — now that the reference is generated outside the
//! model and the observations are passed to the observers step by step.
//!
//! `golden/stateful.json` was written by a throw-away program running the
//! old code (job runners and the particle system); each case below rebuilds
//! the same twin experiment with the new API and compares field by field.
//! The Gauss–Legendre models and the lamppost are compared *bit for bit*;
//! the spring's reference is now generated by the transition matrix T
//! (the discrete flow the observers use) instead of the old `forward()`'s
//! LU solve of the same midpoint step, so its cases are compared to 1e-9
//! relative — round-off, not a change of the algorithm.

